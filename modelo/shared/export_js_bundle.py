#!/usr/bin/env python3
"""
Exports trained ReciBot Neo + ReciBot Flash quantized Int8 weights,
shared 512-token domain vocabulary, 32-intent/12-tool taxonomy, and
42-doc Hybrid BM25 + Dense Vector RAG index into /js/recibot-models.js.
"""

from __future__ import annotations

import json
from pathlib import Path

SHARED_DIR = Path(__file__).resolve().parent
MODELO_DIR = SHARED_DIR.parent
ROOT_DIR = MODELO_DIR.parent
NEO_ART = MODELO_DIR / "recibot-neo" / "artifacts"
FLASH_ART = MODELO_DIR / "recibot-flash" / "artifacts"


def build_js_bundle() -> Path:
    vocab = json.loads((SHARED_DIR / "vocab.json").read_text(encoding="utf-8"))
    taxonomy = json.loads((SHARED_DIR / "taxonomy.json").read_text(encoding="utf-8"))
    rag_index = json.loads((SHARED_DIR / "rag_index.json").read_text(encoding="utf-8"))
    rag_metrics = json.loads((SHARED_DIR / "rag_metrics.json").read_text(encoding="utf-8"))

    neo_int8 = json.loads((NEO_ART / "weights_int8.json").read_text(encoding="utf-8"))
    neo_metrics = json.loads((NEO_ART / "metrics.json").read_text(encoding="utf-8"))
    flash_int8 = json.loads((FLASH_ART / "weights_int8.json").read_text(encoding="utf-8"))
    flash_metrics = json.loads((FLASH_ART / "metrics.json").read_text(encoding="utf-8"))

    # Compact RAG vectors to 3 decimal digits to keep JS bundle lean for WebView mobile startup
    compact_docs = []
    for d in rag_index["docs"]:
        cd = {
            "id": d["id"],
            "intent": d["intent"],
            "title": d["title"],
            "module": d["module"],
            "category": d.get("category", "app"),
            "law_ref": d.get("law_ref", ""),
            "content": d["content"],
            "facts": d.get("facts", []),
            "dl": d["dl"],
            "tf": d["tf"],
            "neo_vec": [round(float(x), 3) for x in d["neo_vec"]],
        }
        if "flash_vec" in d:
            cd["flash_vec"] = [round(float(x), 3) for x in d["flash_vec"]]
        compact_docs.append(cd)

    compact_rag = {
        "k1": rag_index["k1"],
        "b": rag_index["b"],
        "avgdl": rag_index["avgdl"],
        "idf": {k: round(float(v), 3) for k, v in rag_index["idf"].items()},
        "docs": compact_docs,
    }

    neo_e_emb = int(neo_int8["tok_emb.weight"]["shape"][1])
    neo_d_model = int(neo_int8["pos_emb.weight"]["shape"][1])
    neo_ffn_dim = int(neo_int8["blocks.0.ffn1.weight"]["shape"][0])
    neo_n_layers = len([k for k in neo_int8.keys() if k.endswith(".ln1.weight")])
    neo_emb_dim = int(neo_int8["embed_head.weight"]["shape"][0])
    flash_d_emb = int(flash_int8["tok_emb.weight"]["shape"][1])
    flash_hidden = int(flash_int8["fc1.weight"]["shape"][0])
    flash_emb_dim = int(flash_int8["embed_head.weight"]["shape"][0])

    data_blob = {
        "word_to_id": vocab["word_to_id"],
        "max_seq_len": vocab["max_seq_len"],
        "oov_bucket_start": vocab.get("oov_bucket_start", 11808),
        "oov_num_buckets": vocab.get("oov_num_buckets", 8192),
        "neo_dims": {
            "e_emb": neo_e_emb,
            "d_model": neo_d_model,
            "n_heads": 4,
            "head_dim": neo_d_model // 4,
            "ffn_dim": neo_ffn_dim,
            "n_layers": neo_n_layers,
            "emb_dim": neo_emb_dim,
        },
        "flash_dims": {
            "d_emb": flash_d_emb,
            "hidden_dim": flash_hidden,
            "emb_dim": flash_emb_dim,
        },
        "taxonomy": taxonomy,
        "neo": neo_int8,
        "flash": flash_int8,
        "rag": compact_rag,
        "metrics": {
            "neo": neo_metrics,
            "flash": flash_metrics,
            "rag": rag_metrics,
        },
    }

    js_source = f"""/* ==========================================================================
   RECIBOT-MODELS.JS – Trained Dual Neural Models (ReciBot Neo & ReciBot Flash)
   + Shared 512-Token Tokenizer + Hybrid BM25 & Dense Vector RAG Engine
   Auto-generated by modelo/shared/export_js_bundle.py
   ========================================================================== */
(function (root) {{
  const DATA = {json.dumps(data_blob, separators=(",", ":"), ensure_ascii=False)};

  function decodeB64Int8(entry) {{
    let bytes;
    if (typeof Buffer !== 'undefined') {{
      bytes = Buffer.from(entry.q_b64, 'base64');
    }} else {{
      const bin = atob(entry.q_b64);
      bytes = new Uint8Array(bin.length);
      for (let i = 0; i < bin.length; i++) bytes[i] = bin.charCodeAt(i);
    }}
    const out = new Float32Array(bytes.length);
    const s = entry.scale;
    for (let i = 0; i < bytes.length; i++) {{
      const signed = bytes[i] > 127 ? bytes[i] - 256 : bytes[i];
      out[i] = signed * s;
    }}
    return out;
  }}

  const _cache = {{ neo: null, flash: null }};

  function getNeoWeights() {{
    if (_cache.neo) return _cache.neo;
    const dec = {{}};
    for (const [k, v] of Object.entries(DATA.neo)) dec[k] = decodeB64Int8(v);
    _cache.neo = dec;
    return dec;
  }}

  function getFlashWeights() {{
    if (_cache.flash) return _cache.flash;
    const dec = {{}};
    for (const [k, v] of Object.entries(DATA.flash)) dec[k] = decodeB64Int8(v);
    _cache.flash = dec;
    return dec;
  }}

  function normalizeAscii(text) {{
    return String(text || '')
      .normalize('NFD')
      .replace(/[\\u0300-\\u036f]/g, '')
      .toLowerCase()
      .replace(/[^a-z0-9]+/g, ' ')
      .trim();
  }}

  function fnv1a32(str) {{
    let h = 2166136261 >>> 0;
    for (let i = 0; i < str.length; i++) {{
      h ^= str.charCodeAt(i);
      h = Math.imul(h, 16777619) >>> 0;
    }}
    return h;
  }}

  function encodeQuery(text) {{
    const T = DATA.max_seq_len || 32;
    const w2i = DATA.word_to_id;
    const oovStart = DATA.oov_bucket_start || 11808;
    const oovMask = Math.max(1, (DATA.oov_num_buckets || 8192) - 1);
    const clean = normalizeAscii(text);
    const tokens = clean ? clean.split(/\\s+/) : [];
    const ids = new Int32Array(T);
    const mask = new Int32Array(T);
    ids[0] = 2; // <CLS>
    mask[0] = 1;
    let len = 1;
    for (const tok of tokens) {{
      if (len >= T - 1) break;
      ids[len] = (w2i[tok] !== undefined) ? w2i[tok] : (oovStart + (fnv1a32(tok) & oovMask));
      mask[len] = 1;
      len++;
    }}
    if (len < T) {{
      ids[len] = 3; // <SEP>
      mask[len] = 1;
      len++;
    }}
    return {{ ids, mask, activeLen: len, tokens }};
  }}

  function geluTanh(x) {{
    return 0.5 * x * (1.0 + Math.tanh(0.7978845608028654 * (x + 0.044715 * x * x * x)));
  }}

  function layerNormSeq(input, w, b, T, D) {{
    const out = new Float32Array(T * D);
    for (let t = 0; t < T; t++) {{
      const off = t * D;
      let mean = 0;
      for (let d = 0; d < D; d++) mean += input[off + d];
      mean /= D;
      let vs = 0;
      for (let d = 0; d < D; d++) {{
        const df = input[off + d] - mean;
        vs += df * df;
      }}
      const inv = 1.0 / Math.sqrt(vs / D + 1e-5);
      for (let d = 0; d < D; d++) {{
        out[off + d] = ((input[off + d] - mean) * inv) * w[d] + b[d];
      }}
    }}
    return out;
  }}

  function linearSeq(input, W, b, T, inD, outD) {{
    const out = new Float32Array(T * outD);
    for (let t = 0; t < T; t++) {{
      const xO = t * inD;
      const yO = t * outD;
      for (let o = 0; o < outD; o++) {{
        const wO = o * inD;
        let acc = b[o];
        for (let i = 0; i < inD; i++) acc += input[xO + i] * W[wO + i];
        out[yO + o] = acc;
      }}
    }}
    return out;
  }}

  function softmaxTop2(logits) {{
    let first = 0, second = 1;
    if (logits.length > 1 && logits[second] > logits[first]) {{ first = 1; second = 0; }}
    for (let i = 2; i < logits.length; i++) {{
      if (logits[i] > logits[first]) {{ second = first; first = i; }}
      else if (logits[i] > logits[second]) {{ second = i; }}
    }}
    const maxL = logits[first];
    let sumExp = 0;
    const probs = new Float32Array(logits.length);
    for (let i = 0; i < logits.length; i++) {{
      const e = Math.exp(logits[i] - maxL);
      probs[i] = e;
      sumExp += e;
    }}
    return {{
      firstIdx: first,
      firstConf: probs[first] / sumExp,
      secondIdx: second,
      secondConf: logits.length > 1 ? (probs[second] / sumExp) : 0
    }};
  }}

  function sigmoid(x) {{
    return 1.0 / (1.0 + Math.exp(-Math.max(-20, Math.min(20, x))));
  }}

  function minMaxNorm(arr) {{
    let lo = Infinity, hi = -Infinity;
    for (let i = 0; i < arr.length; i++) {{
      if (arr[i] < lo) lo = arr[i];
      if (arr[i] > hi) hi = arr[i];
    }}
    const out = new Float32Array(arr.length);
    if (hi - lo < 1e-8) return out;
    const span = hi - lo;
    for (let i = 0; i < arr.length; i++) out[i] = (arr[i] - lo) / span;
    return out;
  }}

  function retrieveHybridRag(queryTokens, queryEmb, vecField, topK) {{
    const rag = DATA.rag;
    const docs = rag.docs;
    const qTerms = queryTokens.filter(t => t.length >= 2);
    const bm25Raw = new Float32Array(docs.length);
    const denseRaw = new Float32Array(docs.length);

    let qNorm = 0;
    for (let j = 0; j < queryEmb.length; j++) qNorm += queryEmb[j] * queryEmb[j];
    qNorm = Math.sqrt(qNorm) + 1e-8;

    for (let i = 0; i < docs.length; i++) {{
      const d = docs[i];
      const dv = d[vecField] || d.neo_vec;
      let dot = 0;
      for (let j = 0; j < queryEmb.length; j++) dot += (queryEmb[j] / qNorm) * dv[j];
      denseRaw[i] = dot;

      let bScore = 0;
      const dl = Math.max(1, d.dl || 1);
      for (let q = 0; q < qTerms.length; q++) {{
        const term = qTerms[q];
        const f = d.tf[term];
        if (!f) continue;
        const idf = rag.idf[term] || 0;
        bScore += idf * (f * (rag.k1 + 1.0)) / (f + rag.k1 * (1.0 - rag.b + rag.b * (dl / rag.avgdl)));
      }}
      bm25Raw[i] = bScore;
    }}

    const dNorm = minMaxNorm(denseRaw);
    const bNorm = minMaxNorm(bm25Raw);
    const scored = [];
    for (let i = 0; i < docs.length; i++) {{
      const hybridScore = 0.55 * dNorm[i] + 0.45 * bNorm[i];
      scored.push({{
        id: docs[i].id,
        intent: docs[i].intent,
        title: docs[i].title,
        module: docs[i].module,
        category: docs[i].category || 'app',
        law_ref: docs[i].law_ref || '',
        content: docs[i].content,
        facts: docs[i].facts || [],
        hybridScore: Number(hybridScore.toFixed(4)),
        denseScore: Number(denseRaw[i].toFixed(4)),
        bm25Score: Number(bm25Raw[i].toFixed(4)),
      }});
    }}
    scored.sort((a, b) => b.hybridScore - a.hybridScore);
    return scored.slice(0, topK);
  }}

  function _encodeNeoHidden(text) {{
    const dec = getNeoWeights();
    const {{ ids, mask, tokens }} = encodeQuery(text);
    const nd = DATA.neo_dims || {{}};
    const T = DATA.max_seq_len || 32;
    const E = nd.e_emb || 14;
    const D = nd.d_model || 112;
    const H = nd.n_heads || 4;
    const HD = nd.head_dim || Math.floor(D / H);
    const F = nd.ffn_dim || 220;
    const LN = nd.n_layers || 2;
    const ED = nd.emb_dim || 64;

    const x = new Float32Array(T * D);
    const tokEmb = dec['tok_emb.weight'];
    const tokProj = dec['tok_proj.weight'];
    const posEmb = dec['pos_emb.weight'];
    for (let t = 0; t < T; t++) {{
      const tid = ids[t];
      if (tokProj) {{
        const eOff = tid * E;
        for (let d = 0; d < D; d++) {{
          const pOff = d * E;
          let acc = 0;
          for (let e = 0; e < E; e++) acc += tokEmb[eOff + e] * tokProj[pOff + e];
          x[t * D + d] = acc + posEmb[t * D + d];
        }}
      }} else {{
        for (let d = 0; d < D; d++) x[t * D + d] = tokEmb[tid * D + d] + posEmb[t * D + d];
      }}
    }}

    const invSqrt = 1.0 / Math.sqrt(HD);
    const sc = new Float32Array(T);
    for (let l = 0; l < LN; l++) {{
      const xn = layerNormSeq(x, dec[`blocks.${{l}}.ln1.weight`], dec[`blocks.${{l}}.ln1.bias`], T, D);
      const Q = linearSeq(xn, dec[`blocks.${{l}}.wq.weight`], dec[`blocks.${{l}}.wq.bias`], T, D, D);
      const K = linearSeq(xn, dec[`blocks.${{l}}.wk.weight`], dec[`blocks.${{l}}.wk.bias`], T, D, D);
      const V = linearSeq(xn, dec[`blocks.${{l}}.wv.weight`], dec[`blocks.${{l}}.wv.bias`], T, D, D);
      const cat = new Float32Array(T * D);
      for (let t1 = 0; t1 < T; t1++) {{
        for (let h = 0; h < H; h++) {{
          const hOff = h * HD;
          let maxS = -1e9;
          for (let t2 = 0; t2 < T; t2++) {{
            if (!mask[t2]) {{
              sc[t2] = -1e9;
            }} else {{
              let dot = 0;
              for (let k = 0; k < HD; k++) dot += Q[t1 * D + hOff + k] * K[t2 * D + hOff + k];
              sc[t2] = dot * invSqrt;
            }}
            if (sc[t2] > maxS) maxS = sc[t2];
          }}
          let sumE = 0;
          for (let t2 = 0; t2 < T; t2++) {{
            sc[t2] = Math.exp(sc[t2] - maxS);
            sumE += sc[t2];
          }}
          const invE = 1.0 / sumE;
          for (let t2 = 0; t2 < T; t2++) {{
            const wt = sc[t2] * invE;
            for (let k = 0; k < HD; k++) cat[t1 * D + hOff + k] += wt * V[t2 * D + hOff + k];
          }}
        }}
      }}
      const wo = linearSeq(cat, dec[`blocks.${{l}}.wo.weight`], dec[`blocks.${{l}}.wo.bias`], T, D, D);
      for (let i = 0; i < x.length; i++) x[i] += wo[i];

      const xn2 = layerNormSeq(x, dec[`blocks.${{l}}.ln2.weight`], dec[`blocks.${{l}}.ln2.bias`], T, D);
      const ff1 = linearSeq(xn2, dec[`blocks.${{l}}.ffn1.weight`], dec[`blocks.${{l}}.ffn1.bias`], T, D, F);
      for (let i = 0; i < ff1.length; i++) ff1[i] = geluTanh(ff1[i]);
      const ff2 = linearSeq(ff1, dec[`blocks.${{l}}.ffn2.weight`], dec[`blocks.${{l}}.ffn2.bias`], T, F, D);
      for (let i = 0; i < x.length; i++) x[i] += ff2[i];
    }}

    const xOut = layerNormSeq(x, dec['norm_out.weight'], dec['norm_out.bias'], T, D);
    let actCnt = 0;
    for (let t = 0; t < T; t++) actCnt += mask[t];
    const invCnt = 1.0 / Math.max(1, actCnt);
    const pooled = new Float32Array(D);
    for (let d = 0; d < D; d++) {{
      let sm = 0;
      for (let t = 0; t < T; t++) if (mask[t]) sm += xOut[t * D + d];
      pooled[d] = 0.5 * xOut[d] + 0.5 * (sm * invCnt);
    }}
    const emb = linearSeq(pooled, dec['embed_head.weight'], dec['embed_head.bias'], 1, D, ED);
    return {{ dec, D, tokens, pooled, emb }};
  }}

  function inferNeo(text) {{
    const t0 = (typeof performance !== 'undefined' && performance.now) ? performance.now() : Date.now();
    const {{ dec, D, tokens, pooled, emb }} = _encodeNeoHidden(text);

    const ilog = linearSeq(pooled, dec['intent_head.weight'], dec['intent_head.bias'], 1, D, DATA.taxonomy.intents.length);
    const tlog = linearSeq(pooled, dec['tool_head.weight'], dec['tool_head.bias'], 1, D, DATA.taxonomy.tools.length);
    const dlog = linearSeq(pooled, dec['depth_head.weight'], dec['depth_head.bias'], 1, D, DATA.taxonomy.depth_labels.length);

    const topI = softmaxTop2(ilog);
    const depthTop = softmaxTop2(dlog);
    const activeTools = [];
    for (let i = 0; i < tlog.length; i++) {{
      const p = sigmoid(tlog[i]);
      if (p >= 0.42) activeTools.push({{ name: DATA.taxonomy.tools[i], score: Number(p.toFixed(4)) }});
    }}
    activeTools.sort((a, b) => b.score - a.score);

    const ragDocs = retrieveHybridRag(tokens, emb, 'neo_vec', 5);
    const intentDef = DATA.taxonomy.intents[topI.firstIdx];
    const secDef = DATA.taxonomy.intents[topI.secondIdx];
    const now = (typeof performance !== 'undefined' && performance.now) ? performance.now() : Date.now();

    return {{
      model: 'neo',
      intent: intentDef.name,
      intentTitle: intentDef.title,
      confidence: Number(topI.firstConf.toFixed(4)),
      secondIntent: secDef ? secDef.name : null,
      secondConfidence: Number(topI.secondConf.toFixed(4)),
      tools: activeTools,
      depth: DATA.taxonomy.depth_labels[depthTop.firstIdx],
      depthConfidence: Number(depthTop.firstConf.toFixed(4)),
      ragTopDocs: ragDocs,
      latencyMs: Number((now - t0).toFixed(2)),
    }};
  }}

  function _encodeFlashHidden(text) {{
    const dec = getFlashWeights();
    const {{ ids, activeLen, tokens }} = encodeQuery(text);
    const fd = DATA.flash_dims || {{}};
    const D = fd.d_emb || 8;
    const F = D * 2;
    const H = fd.hidden_dim || 88;
    const ED = fd.emb_dim || 64;
    const tokEmb = dec['tok_emb.weight'];
    const feat = new Float32Array(F);
    for (let d = 0; d < D; d++) feat[D + d] = -1e9;

    for (let t = 0; t < activeLen; t++) {{
      const off = ids[t] * D;
      for (let d = 0; d < D; d++) {{
        const v = tokEmb[off + d];
        feat[d] += v;
        if (v > feat[D + d]) feat[D + d] = v;
      }}
    }}
    const inv = 1.0 / Math.max(1, activeLen);
    for (let d = 0; d < D; d++) feat[d] *= inv;

    const fc1W = dec['fc1.weight'], fc1B = dec['fc1.bias'];
    const hid = new Float32Array(H);
    for (let h = 0; h < H; h++) {{
      const wOff = h * F;
      let acc = fc1B[h];
      for (let i = 0; i < F; i++) acc += feat[i] * fc1W[wOff + i];
      hid[h] = acc > 0 ? acc : 0;
    }}
    const emb = linearSeq(hid, dec['embed_head.weight'], dec['embed_head.bias'], 1, H, ED);
    return {{ dec, H, tokens, hid, emb }};
  }}

  function inferFlash(text) {{
    const t0 = (typeof performance !== 'undefined' && performance.now) ? performance.now() : Date.now();
    const {{ dec, H, tokens, hid, emb }} = _encodeFlashHidden(text);

    const ilog = linearSeq(hid, dec['intent_head.weight'], dec['intent_head.bias'], 1, H, DATA.taxonomy.intents.length);
    const tlog = linearSeq(hid, dec['tool_head.weight'], dec['tool_head.bias'], 1, H, DATA.taxonomy.tools.length);

    const topI = softmaxTop2(ilog);
    const activeTools = [];
    for (let i = 0; i < tlog.length; i++) {{
      const p = sigmoid(tlog[i]);
      if (p >= 0.45) activeTools.push({{ name: DATA.taxonomy.tools[i], score: Number(p.toFixed(4)) }});
    }}
    activeTools.sort((a, b) => b.score - a.score);

    const ragDocs = retrieveHybridRag(tokens, emb, 'flash_vec', 3);
    const intentDef = DATA.taxonomy.intents[topI.firstIdx];
    const secDef = DATA.taxonomy.intents[topI.secondIdx];
    const now = (typeof performance !== 'undefined' && performance.now) ? performance.now() : Date.now();

    return {{
      model: 'flash',
      intent: intentDef.name,
      intentTitle: intentDef.title,
      confidence: Number(topI.firstConf.toFixed(4)),
      secondIntent: secDef ? secDef.name : null,
      secondConfidence: Number(topI.secondConf.toFixed(4)),
      topTool: activeTools.length > 0 ? activeTools[0].name : null,
      tools: activeTools,
      ragTopDocs: ragDocs,
      ragTopDoc: ragDocs[0] || null,
      latencyMs: Number((now - t0).toFixed(2)),
    }};
  }}

  function retrieveRag(text, modelType = 'neo', topK = 5) {{
    if (modelType === 'flash') {{
      const {{ tokens, emb }} = _encodeFlashHidden(text);
      return retrieveHybridRag(tokens, emb, 'flash_vec', topK);
    }}
    const {{ tokens, emb }} = _encodeNeoHidden(text);
    return retrieveHybridRag(tokens, emb, 'neo_vec', topK);
  }}

  const api = {{
    inferNeo,
    inferFlash,
    retrieveRag,
    encodeQuery,
    normalizeAscii,
    NEO_METRICS: DATA.metrics.neo,
    FLASH_METRICS: DATA.metrics.flash,
    RAG_METRICS: DATA.metrics.rag,
    TAXONOMY: DATA.taxonomy,
    IDENTITIES: DATA.taxonomy.identities || {{}},
  }};

  root.ReciBotModels = api;
  if (typeof module !== 'undefined' && module.exports) {{
    module.exports = api;
  }}
}})(typeof window !== 'undefined' ? window : globalThis);
"""

